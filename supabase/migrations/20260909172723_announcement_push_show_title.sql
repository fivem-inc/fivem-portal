-- 社内お知らせの「件名をスマホの通知に出すか」を1件ごとに選べるようにする。
--
-- 背景（2026-09-09）:
--   プッシュの文面は長らく「状態語 + 件数」しか使えなかった（Android Chrome が
--   それ以外を警告表示に置き換えていたため）。同日の実機テストで、いまの Chrome では
--   文章も表示されることが分かったため、本文を意味の通る文章に変更した。
--   あわせて「社内お知らせだけは件名そのものを出したい」というユーザー要望に対応する。
--
-- 🚨 なぜ1件ごとの切り替えが要るか:
--   プッシュはロック画面に出る＝スマホを開かなくても、そばにいる人に見える。
--   「◯◯さんの退職について」「給与改定の件」のような件名は出すべきでない。
--   出すかどうかは、書いた本人がその場で決められるようにする。
--
-- 🚨 連絡板には同じ仕組みを入れていない（個人あてメッセージの用件が漏れるため）。
--   件名を出せるのは社内お知らせだけ。push-dispatch 側でも tagKey で限定している。

alter table announcements
  add column if not exists push_show_title boolean not null default true;

comment on column announcements.push_show_title is
  'スマホのプッシュ通知に件名そのものを出すか。false なら「社内お知らせが届いています」に伏せる。ロック画面に出るため、見られて困る件名のときは false にする（2026-09-09 追加）';

-- 既存の2件はいずれも「【ファイブMスタッフサイト アップデートのお知らせ】…」で、
-- 出て困る内容ではないため既定 true のままとする（作成時通知は既に送信済みで、
-- 影響するのは remind_push が有効な行の期限リマインドのみ）。
