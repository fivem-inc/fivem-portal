-- 場所予約：スタッフに読み仮名を持たせる（2026-09-04 ユーザー指示）
--
-- きっかけ：予約フォームの担当スタッフを名前で絞り込めるようにしたが、
--   漢字でしか引けなかった。ひらがな・カタカナ・半角カナでも探せるようにする。
--
-- 🚨 **ひらがなで持つ**。表示のときだけカタカナに直す、という既存の方針に合わせる
--    （お客様のふりがなと同じ持ち方。持ち方を変えると表示側も直すことになり、
--     片方だけ直して崩れる）。検索は打った文字をひらがなに直して比べる。
--
-- 🚨 **初期値は入れない（空のまま）**。漢字から読みは作れない（同じ漢字でも読みが
--    複数ある）。推測で入れるとスタッフの名前を間違えて扱うことになる。
--    基本設定 → スタッフ から1人ずつ入れてもらう。
--    空のままでも、これまでどおり漢字では引ける（絞り込みが効かないだけ）。
--
-- ロールバック手順:
--   alter table room_staff drop column if exists kana;
-- ============================================================

alter table room_staff
  add column if not exists kana text;

comment on column room_staff.kana is
  'お名前の読み（ひらがなで持つ・2026-09-04〜）。担当スタッフの絞り込みに使う。空でもよい';

