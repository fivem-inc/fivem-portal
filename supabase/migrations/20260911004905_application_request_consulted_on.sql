-- 申請依頼に「相談した日」を持たせる
--   （2026-09-10 ユーザー要望「9/9 に相談した 9/10 の…」／2026-09-11 実装・案①で確定）
--
-- 依頼カードに「9/9（月）に相談した 9/10（火）の残業を申請してください」と出せるようにする。
--
-- 🚨 **created_at（依頼を作った日）では代用できない。** 口頭で相談した日と、そのあと画面から
--    依頼を作った日は別もので、数日ずれることがある。ずれた日付を「相談した日」として出すと
--    画面が嘘をつく（このリポジトリで何度も起きている「同じ意味の値を別のもので代用する」事故）。
-- 🚨 **任意（null 可）にする。** 口頭の相談を経ずに依頼することもあるので、必須にすると
--    存在しない日付を入れさせることになる。空のときはカードに何も出さない。
-- 🚨 **時刻は持たない（date）。** 「何日に話したか」で足りる。時刻を持つと、UTC で切って
--    前日になる事故（toISOString().slice(0,10) の罠）の的が1つ増える。
-- 🚨 **新しい許可（ポリシー）は足していない。** 既存の appreq_insert
--    （requester_id = auth.uid() かつ「申請の依頼」の機能権限あり）だけで書ける。
--    列を足すだけなので、行の見え方は1件も変わらない。

alter table public.application_requests
  add column if not exists consulted_on date;

comment on column public.application_requests.consulted_on is
  '上長が本人と口頭で相談した日（任意・null可）。依頼を作った日（created_at）とは別もの。依頼カードに「◯/◯（曜）に相談した」と出すためだけに使う';
