-- 退職のチェック表に「対象外」を足す（2026-09-21 ユーザー承認）
--
-- きっかけ：チェック項目は全員に同じものが出るが、人によって**そもそも無い**項目がある
--           （鍵を持っていない・制服がない・名刺を作っていない など）。
--           いまは「済み」にするしか片付ける手段が無く、やっていないのに済みと記録されてしまう。
--
-- 【決まったこと（ユーザー確定）】
--   ・呼び名は「**対象外**」（案：対象外／該当なし／不要 の3案から）
--   ・既定は今までどおり**全項目を出す**。人ごとに、その都度「対象外」にする
--   ・押すところは**行の右端に小さく**。押すとその場で確認を出す（誤爆で必須が静かに消えないように）
--
-- 🚨 新しい表は作らない。いまの retire_checklist_checks に列を1つ足すだけ。
-- 🚨 **残り件数の数え方は1文字も直さない**。数え方は「その項目に行があれば残りに数えない」
--    （画面は lib/retire.ts の retireRemaining、朝9時の通知は retire_checklist_notify の
--     not exists）なので、対象外も行を作れば**自動的に残りから外れる**。
--    ＝退職日の朝9時の通知にも、そのまま効く。
-- 🚨 「誰がいつ対象外にしたか」は、済みと同じ done_by / done_at にそのまま残る。

alter table public.retire_checklist_checks
  add column if not exists na boolean not null default false;

comment on column public.retire_checklist_checks.na is
  'その人にはこの項目が無い（対象外）。false＝済み。'
  '🚨 どちらも「片付いた」扱いで、残り件数からは外れる。見た目だけを分ける';

-- 既存の記録はすべて「済み」のまま（対象外は0件から始まる）

