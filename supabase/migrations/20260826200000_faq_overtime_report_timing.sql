--
-- 直す理由:
--   ① 「事前申請が受理されると…ボタンが出ます」は 2026-08-25 に
--      「受理を待たずに実績を報告できる」ようにした時点で古くなっていた（直し残し）。
--   ② 2026-08-26 の変更で、ボタンが出るのは「その日の勤務が終わるころ」
--      （通常シフトの終了と予定の終了の早いほう）と明確になった。
--      それまでは勤務日の翌日にならないと出なかったため、
--      「勤務が終わったのに報告できない」という問い合わせが実際に発生した。
--
-- 変更は本文の書き出し1文のみ。①〜③と末尾の一文はそのまま。
