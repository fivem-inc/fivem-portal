-- 画面は components/ClockReasonPicker。入口のボタンは「🕐 打刻を忘れた・遅れた（残業ではない）はこちら」

-- 打刻を忘れて退勤時刻がずれた。残業はしていない → 出勤の打刻忘れも入るので問いの文も直す
update public.faq_topics t
   set question = '打刻を忘れた・遅れた（出勤・退勤）。残業はしていない', updated_at = now()
  from public.faq_answers a
 where a.id = '0e58a01c-3eb8-4aa9-a205-950436d26066' and t.id = a.topic_id
   and t.question = '打刻を忘れて退勤時刻がずれた。残業はしていない';

update public.faq_answers
   set body = replace(replace(body,
         '「事後報告」→日付選択→「🕐 残業ではありません（打刻が遅れただけ）」を選びます。',
         '「事後報告」→日付選択→「🕐 打刻を忘れた・遅れた（残業ではない）はこちら」を押します。' || chr(10) || chr(10) ||
         '「何がありましたか？」で、①出勤の打刻を忘れた ②退勤の打刻を忘れた ③打刻が遅れた・早かった（残業ではない）から選びます。③のときは理由（同僚と話していた／私用で残っていた／その他）も選びます。'),
         '打刻時刻（任意）と理由（必須。打刻を忘れた／同僚と話していた／私用で残っていた／その他）だけ入力すれば記録でき、',
         '押せた方の打刻時刻（任意）を入れれば記録でき、'),
       updated_at = now()
 where id = '0e58a01c-3eb8-4aa9-a205-950436d26066'
   and body like '%「🕐 残業ではありません（打刻が遅れただけ）」を選びます。%'
   and body like '%理由（必須。打刻を忘れた／同僚と話していた／私用で残っていた／その他）だけ入力すれば記録でき、%';

