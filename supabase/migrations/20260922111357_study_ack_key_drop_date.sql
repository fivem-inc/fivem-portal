-- 取り消すとき
-- ─────────────────────────────────────────
--   🚨 落とした日付は元に戻せない（どの日だったかが残らない）。
--      戻す必要が出たら、該当の「確認した」を画面で押し直してもらうこと。
--      画面側（studySessions.ts の key）を戻すだけなら、記録は新しい鍵のまま残る。
