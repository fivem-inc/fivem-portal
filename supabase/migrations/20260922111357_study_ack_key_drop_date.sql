-- 勉強会の「確認した」が翌日に外れる不具合の後始末（2026-09-22）
--
-- 【何が起きていたか】
--   `lib/studySessions.ts` が、⚠️ の鍵に **since（この日から）を混ぜて**いた。
--     key = `種類|誰|中身|since`
--   since は `max(版の開始日, 画面が見ている日)` で、画面が見ている日は**今日**。
--   つまり **日が変わるだけで鍵が変わり、押した「確認した」が翌日には外れて警告がぶり返す**。
--
--   🚨 引き継ぎには「本番の勉強会は0件なので実害はまだ無い」と書かれていたが**誤り**だった。
--      実際には版が1件・「確認した」が1件（`no_shift|705a09b8-…||2026-09-17`）あり、
--      9/18 の時点ですでに外れていた。
--
-- 【直し方】
--   画面側は `key: k`（種類|誰|中身）に直した。掃除当番（cleaningRoster.ts:138）は
--   最初から内容だけで鍵を作っており、そちらに合わせた形。
--   🚨 この migration は**すでに保存されている記録の鍵から、末尾の日付を落とす**だけ。
--      落とさないと、せっかく押した「確認した」が新しい鍵と一致せず、永久にぶり返す。
--
-- 🚨 対象は「末尾が |YYYY-MM-DD の行」だけ。それ以外の行には触らない。

update public.study_session_acks
   set issue_key = regexp_replace(issue_key, '\|\d{4}-\d{2}-\d{2}$', '')
 where issue_key ~ '\|\d{4}-\d{2}-\d{2}$';

