■ 申請を出していない日
・「業務をしていました」→ 回答の確定後にそのまま残業報告へ進めます。確認された側の時刻（終わり・開始）は空欄になっているので、打刻ではなく実際に勤務を終えた（始めた）時刻を入れてください
