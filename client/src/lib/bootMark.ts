// 起動の「どこで時間がかかっているか」を測るための通過時刻の印（2026-09-12）
//
// 【なぜ要るか】
// 実機で測ったら、絵が出るのは 0.39秒なのに、ログイン確認の通信が始まるのが **2.92秒**だった。
// 🚨 **間の約2.4秒、何も起きていない**。これが「開くのが遅い」の本体だが、
//    ブラウザが自動で記録するのは通信だけなので、**通信していない間のことは分からない**。
//    → 通り道に印を置いて、どこで止まっているかを見えるようにする。
//
// 🚨 これは**印を置くだけ**で、処理は1つも増やしていない（保存もしない・通信もしない）。
//    印は管理者だけが見る「起動の内訳」（components/BootTiming.tsx）に出る。
//
// 🚨 対応していない端末・計測を止めている設定でも落ちないように、必ず握りつぶす。
//    ここで例外が出ると**アプリが起動しなくなる**（起動のいちばん手前で呼ぶため）。

export function bootMark(name: string): void {
  try {
    performance.mark(name);
  } catch {
    /* 測れない端末では何もしない。起動を止めないことが最優先 */
  }
}
